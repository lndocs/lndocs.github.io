#!/usr/bin/env node
// Builds the env and endpoint reference pages from data that CI dumps from the
// pinned lnbits/lnbits image (scripts/reference/settings.json and openapi.json).
// Don't edit the generated pages by hand: change this script and re-run it.
// Usage: node scripts/gen-reference.mjs
import fs from 'node:fs';

const dir = new URL('./reference/', import.meta.url);
const settings = JSON.parse(fs.readFileSync(new URL('settings.json', dir), 'utf8'));
const openapi = JSON.parse(fs.readFileSync(new URL('openapi.json', dir), 'utf8'));
const version = fs.readFileSync(new URL('./lnbits-version.txt', import.meta.url), 'utf8').trim();

const front = (pos, title, description) => `---
sidebar_position: ${pos}
title: ${title}
description: ${description}
last_update:
  date: DATE
verified_with: ${version}
---

{/* Generated by scripts/gen-reference.mjs from the lnbits/lnbits:${version} image. Don't edit by hand. */}
`;

const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (s) => '`' + cell(s).replace(/`/g, "'") + '`';
const text = (s) => cell(s).replace(/[{}<>]/g, (c) => ({ '{': '&#123;', '}': '&#125;', '<': '&lt;', '>': '&gt;' })[c]);

function showDefault(v) {
  if (v === null || v === undefined) return '(unset)';
  if (v === '') return '`""`';
  const s = typeof v === 'string' ? v : JSON.stringify(v);
  return code(s.length > 70 ? s.slice(0, 67) + '…' : s);
}

// ---- env reference ----------------------------------------------------------
const label = (g) => g
  .replace(/FundingSource$/, ' (funding source)')
  .replace(/FiatProvider$/, ' (fiat provider)')
  .replace(/AuthSettings$/, ' auth')
  .replace(/Settings$/, '')
  .replace(/([a-z])([A-Z])/g, '$1 $2')
  .trim();

const groups = new Map();
for (const s of [...settings].sort((a, b) => a.name.localeCompare(b.name))) {
  const g = label(s.group || 'Other');
  if (!groups.has(g)) groups.set(g, []);
  groups.get(g).push(s);
}
const editable = settings.filter((s) => s.editable).length;

let env = front(3, 'Environment variable reference', `Every LNbits ${version} setting, its type and default, and whether the Admin UI manages it.`);
env += `
# Environment variable reference

All ${settings.length} settings that LNbits ${version} reads, generated from the settings model in the official image. For what they do and when to change them, see [Environment Variables](/docs/configuration/environment).

- **Admin UI: yes** (${editable} settings): after the first start the value lives in the database, and the Admin UI wins over \`.env\` while \`LNBITS_ADMIN_UI=true\` (the default). See [Admin UI](/docs/configuration/admin-ui).
- **Admin UI: no** (${settings.length - editable} settings): always read from the environment or \`.env\`, at every start.
- Names are case-insensitive. Lists take JSON (\`["a","b"]\`) or comma-separated values.
- Defaults are shown as declared; long ones are cut short.

`;
for (const [g, rows] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
  env += `## ${g}\n\n| Variable | Type | Default | Admin UI |\n|---|---|---|---|\n`;
  for (const s of rows) env += `| ${s.env.map(code).join(', ')} | ${code(s.type)} | ${showDefault(s.default)} | ${s.editable ? 'yes' : 'no'} |\n`;
  env += '\n';
}

// ---- endpoint reference -----------------------------------------------------
function auth(op, path) {
  const kinds = new Set((op.security || []).flatMap((x) => Object.keys(x)));
  const out = [];
  if (kinds.has('APIKeyHeader') || kinds.has('APIKeyQuery')) out.push('wallet key');
  if (kinds.has('HTTPBearer') || kinds.has('OAuth2PasswordBearer')) out.push('account token');
  if (!out.length) return 'none';
  if (/^\/(admin|users|audit)\//.test(path) || path.startsWith('/node/api/')) return out.join(' or ') + ' (admin)';
  return out.join(' or ');
}

const byTag = new Map();
let count = 0;
for (const [path, ops] of Object.entries(openapi.paths)) {
  for (const [method, op] of Object.entries(ops)) {
    const tag = (op.tags && op.tags[0]) || 'Other';
    if (!byTag.has(tag)) byTag.set(tag, []);
    byTag.get(tag).push({ method: method.toUpperCase(), path, summary: op.summary || '', auth: auth(op, path), deprecated: op.deprecated });
    count++;
  }
}

let api = front(9, 'Endpoint reference', `Every LNbits ${version} API endpoint, from the OpenAPI schema of the official image.`);
api += `
# Endpoint reference

All ${count} operations in the OpenAPI schema of LNbits ${version}, generated from \`/openapi.json\` on the official image. Your own instance serves the same schema, with request and response models, at \`/openapi.json\` and \`/docs\`.

The **Auth** column comes from the schema. Two limits:

- The schema doesn't say *which* wallet key a route needs. Routes that spend or change things need the **admin key**, while reads and creating invoices accept the **invoice key**. See [Authentication](/docs/api/authentication).
- An account token is a bearer token or the login cookie. Routes under \`/admin\`, \`/users\`, \`/audit\` and \`/node/api\` are marked **(admin)**: they need an admin account, and some of them need the Super User. Other routes may check roles too (for example, installing extensions needs an admin), so treat the column as a minimum. See [Users](/docs/api/users).

Routes that installed extensions add are not listed. The [API claims workflow](https://github.com/lndocs/lndocs.github.io/actions/workflows/claims.yml) regenerates this page from the image and fails if it is out of date.

`;
for (const [tag, rows] of [...byTag].sort(([a], [b]) => a.localeCompare(b))) {
  api += `## ${text(tag)}\n\n| Method | Path | Summary | Auth |\n|---|---|---|---|\n`;
  for (const r of rows.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method))) {
    api += `| ${r.method} | ${code(r.path)} | ${text(r.summary)}${r.deprecated ? ' (deprecated)' : ''} | ${r.auth} |\n`;
  }
  api += '\n';
}

// Keep last_update stable unless the content changed, so CI can diff the output.
function write(rel, body) {
  const url = new URL(rel, import.meta.url);
  const old = fs.existsSync(url) ? fs.readFileSync(url, 'utf8') : '';
  const oldDate = (old.match(/^  date: (\S+)$/m) || [])[1];
  const same = oldDate && old === body.replace('DATE', oldDate);
  fs.writeFileSync(url, body.replace('DATE', same ? oldDate : new Date().toISOString().slice(0, 10)));
}
write('../docs/configuration/env-reference.md', env);
write('../docs/api/endpoint-reference.md', api);
console.log(`env-reference: ${settings.length} settings; endpoint-reference: ${count} operations`);
